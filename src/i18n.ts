/** The name of a language in the language of the interface (the browser knows them); the code when it does not. */
export function languageName(code: string): string {
  try {
    const name = new (Intl as any).DisplayNames([current], { type: "language" }).of(code);
    return typeof name === "string" && name !== "" ? name.charAt(0).toLocaleUpperCase(current) + name.slice(1) : code;
  } catch { return code; }
}

/** The options of a picker of languages, sorted by their names. */
export function languageOptions(codes: string[]): Array<{ data: string; label: string }> {
  return codes.map((code) => ({ data: code, label: languageName(code) })).sort((a, b) => a.label.localeCompare(b.label, current));
}
