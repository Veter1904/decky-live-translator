/** The language of the interface for a Steam locale ("ru", "pt-BR", "schinese", "koreana", "latam" ...); null when there is none for it. */
export function interfaceLanguageFor(locale: string | undefined | null): UiLang | null {
  const code = String(locale ?? "").toLowerCase();
  const names: Record<string, UiLang> = { english: "en", ukrainian: "uk", russian: "ru", german: "de", french: "fr", spanish: "es", latam: "es", italian: "it", brazilian: "pt", portuguese: "pt", polish: "pl", turkish: "tr", schinese: "zh", tchinese: "zh", japanese: "ja", koreana: "ko" };
  if (code in names) return names[code];
  const short = code.slice(0, 2);
  return (UI_LANGUAGES.find((language) => language.code === short)?.code) ?? null;
}

/** The language of Steam: the Steam client keeps its locales in LocalizationManager; the language of the browser is the second choice. */
export function steamLanguage(): UiLang {
  try {
    const manager = (globalThis as any).window?.LocalizationManager ?? (globalThis as any).LocalizationManager;
    const locales: string[] = manager?.m_rgLocalesToUse ?? [];
    for (const locale of locales) {
      const found = interfaceLanguageFor(locale);
      if (found !== null) return found;
    }
    const navigatorLanguages: string[] = (globalThis as any).navigator?.languages ?? [];
    for (const locale of navigatorLanguages) {
      const found = interfaceLanguageFor(locale);
      if (found !== null) return found;
    }
  } catch { /* the language of Steam is not known: English */ }
  return "en";
}

let current: UiLang = "en";

/** Sets the language: "auto" is the one of Steam, otherwise a code of UI_LANGUAGES. Returns the language that is used. */
export function setUiLanguage(preference: string | undefined): UiLang {
  const wanted = UI_LANGUAGES.find((language) => language.code === preference)?.code;
  current = wanted ?? steamLanguage();
  return current;
}

export function uiLanguage(): UiLang {
  return current;
}

/** A string of the interface in the language that is set (English when the language has no such string), with {name} places filled in. */
export function t(key: StringKey, values?: Record<string, string | number>): string {
  const text = STRINGS[current]?.[key] ?? en[key];
  return values === undefined ? text : text.replace(/\{(\w+)\}/g, (whole, name) => (name in values ? String(values[name]) : whole));
}

